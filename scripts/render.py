"""Render the entry tables in README.md from data/entries.json.

The README holds hand-written framing text plus one generated block between
the BEGIN and END markers. This script rewrites only that block.

    python scripts/render.py           # rewrite README.md in place
    python scripts/render.py --check   # exit 1 if README.md is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "entries.json"
README = ROOT / "README.md"

BEGIN = "<!-- BEGIN ENTRIES: generated by scripts/render.py, do not edit by hand -->"
END = "<!-- END ENTRIES -->"


def load(path: Path = DATA) -> dict:
    """Read the data file; raises OSError or ValueError (including JSONDecodeError)."""
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def describe_error(path: Path, exc: Exception) -> str:
    """One line naming the file and what is wrong with it, for the scripts' error output."""
    if isinstance(exc, json.JSONDecodeError):
        return f"{path}: line {exc.lineno} column {exc.colno}: {exc.msg}"
    if isinstance(exc, OSError):
        return f"{path}: {exc.strerror or exc}"
    return f"{path}: {exc}"


def anchor(title: str) -> str:
    """GitHub-style heading anchor for a section title."""
    out = []
    for ch in title.lower():
        if ch.isalnum() or ch in "-_":
            out.append(ch)
        elif ch == " ":
            out.append("-")
    return "".join(out)


# Line breaks and other control characters; any of them would end a table row on GitHub.
CONTROL_RE = re.compile(r"[\x00-\x1f\x7f-\x9f\u2028\u2029]+")


def cell(text: str) -> str:
    """Make text safe inside one Markdown table cell: control characters become a space, and
    backslashes and pipes are escaped so that both show as written."""
    text = CONTROL_RE.sub(" ", str(text))
    return text.replace("\\", "\\\\").replace("|", "\\|").strip()


def licence_cell(entry: dict) -> str:
    """The Licence column: the licence, then the venue when there is one."""
    lic = entry["licence"]
    venue = entry.get("venue")
    return f"{lic}; {venue}" if venue else lic


def licence_table(entries: list[dict]) -> list[str]:
    """Count entries per stated licence, split into code/data and papers."""
    counts: dict[str, list[int]] = {}
    for e in entries:
        lic = e["licence"].replace(" (paper)", "")
        col = 1 if e["kind"] == "paper" else 0
        counts.setdefault(lic, [0, 0])[col] += 1
    rows = sorted(counts.items(), key=lambda kv: (-sum(kv[1]), kv[0].lower()))
    lines = ["| Licence as stated | Code and data | Papers |", "|---|---|---|"]
    lines += [f"| {cell(lic)} | {a} | {b} |" for lic, (a, b) in rows]
    return lines


def kind_line(entries: list[dict]) -> str:
    """One line counting entries per kind, largest first."""
    kinds: dict[str, int] = {}
    for e in entries:
        kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
    parts = [f"{k} {n}" for k, n in sorted(kinds.items(), key=lambda kv: (-kv[1], kv[0]))]
    return "By kind: " + ", ".join(parts) + "."


def render_block(data: dict) -> str:
    """The generated part of the README: contents, one table per section, licence counts."""
    sections = data["sections"]
    entries = data["entries"]
    lines = [BEGIN, "", "## Contents", ""]
    for sec in sections:
        n = sum(1 for e in entries if e["section"] == sec["id"])
        lines.append(f"- [{sec['title']}](#{anchor(sec['title'])}) ({n})")
    lines.append(f"- [Licences at a glance](#{anchor('Licences at a glance')})")
    lines.append("")
    for sec in sections:
        rows = [e for e in entries if e["section"] == sec["id"]]
        rows.sort(key=lambda e: (e["year"], e["name"].lower()))
        lines += [f"## {sec['title']}", "", sec["blurb"], ""]
        lines.append("| Name | Year | Kind | Licence | What it is |")
        lines.append("|---|---|---|---|---|")
        for e in rows:
            lines.append(
                f"| [{cell(e['name'])}]({e['url']}) | {e['year']} | {e['kind']} "
                f"| {cell(licence_cell(e))} | {cell(e['summary'])} |"
            )
        lines.append("")
    lines += ["## Licences at a glance", "",
              "Counted from the data file. For papers this is the licence of the text on arXiv.", ""]
    lines += licence_table(entries)
    lines += ["", kind_line(entries), ""]
    lines.append(fetched_line(entries, data["fetched"]))
    lines += ["", END]
    return "\n".join(lines)


def fetched_line(entries: list[dict], latest: str) -> str:
    """State the fetch dates honestly: one date if they agree, else the range."""
    first = min((e["fetched"] for e in entries), default=latest)
    if first == latest:
        return f"{len(entries)} entries, all fetched on {latest}."
    return f"{len(entries)} entries, fetched between {first} and {latest}."


def splice(readme_text: str, block: str) -> str:
    """Replace the text between the BEGIN and END markers; ValueError if they are missing."""
    start = readme_text.find(BEGIN)
    stop = readme_text.find(END)
    if start == -1 or stop == -1 or stop < start:
        raise ValueError("README.md is missing the BEGIN/END entry markers")
    return readme_text[:start] + block + readme_text[stop + len(END):]


def rendered_readme(data: dict, readme_text: str) -> str:
    """The README as it should be for this data."""
    return splice(readme_text, render_block(data))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report whether README.md is current")
    ap.add_argument("--data", type=Path, default=DATA,
                    help="path to entries.json (default data/entries.json)")
    ap.add_argument("--readme", type=Path, default=README,
                    help="path to README.md (default README.md)")
    args = ap.parse_args(argv)
    try:
        data = load(args.data)
    except (OSError, ValueError) as exc:
        print(describe_error(args.data, exc), file=sys.stderr)
        return 2
    try:
        current = args.readme.read_text(encoding="utf-8")
    except (OSError, ValueError) as exc:
        print(describe_error(args.readme, exc), file=sys.stderr)
        return 2
    try:
        new = rendered_readme(data, current)
    except ValueError as exc:
        print(describe_error(args.readme, exc), file=sys.stderr)
        return 2
    except (KeyError, TypeError, AttributeError):
        print(f"{args.data}: records are not in the expected shape; run: python scripts/validate.py",
              file=sys.stderr)
        return 2
    if args.check:
        if new != current:
            print("README.md is out of date; run: python scripts/render.py", file=sys.stderr)
            return 1
        print("README.md is in sync with the data file")
        return 0
    if new != current:
        args.readme.write_text(new, encoding="utf-8")
        print("README.md updated")
    else:
        print("README.md already current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
